import fs from "node:fs";
import assert from "node:assert/strict";
const html=fs.readFileSync(new URL("../public/oldman/index.html",import.meta.url),"utf8");
const server=fs.readFileSync(new URL("../server.js",import.meta.url),"utf8");
assert.match(html,/<html lang="pt-BR">/);
assert.match(html,/name="viewport"/);
assert.match(html,/name="robots" content="noindex,nofollow"/);
assert.match(html,/Old Man/);
assert.match(html,/id="fila"/);
assert.match(html,/id="sobre"/);
assert.match(html,/id="informacoes"/);
assert.match(html,/id="queue-count"[^>]*>—</);
assert.match(html,/Integração em preparação/);
assert.match(html,/Cardápio em atualização/);
assert.match(html,/Sem dados pessoais/);
assert.doesNotMatch(html,/João Silva|5511912345678|joao\.silva@gmail\.com/);
assert.doesNotMatch(html,/getin\.app\/sao-paulo\/holy-burger/);
assert.ok(server.includes('express.static(path.join(__dirname, "public")'));
console.log("PASS: página pública isolada, responsiva em rascunho, sem dados individuais ou fila fictícia.");
