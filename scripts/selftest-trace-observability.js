import fs from "node:fs";
const source=fs.readFileSync(new URL("../server.js",import.meta.url),"utf8");
const smoke=fs.readFileSync(new URL("./smoke-staging-gate.js",import.meta.url),"utf8");
const checks=[];
const check=(name,ok)=>checks.push({name,ok:Boolean(ok)});
check("dispatch trace column",source.includes("ADD COLUMN IF NOT EXISTS trace_id TEXT"));
check("operational events table",source.includes("CREATE TABLE IF NOT EXISTS operational_events"));
check("trace indexes",source.includes("operational_events_trace_idx")&&source.includes("dispatches_trace_idx"));
check("system errors traced",source.includes("INSERT INTO system_errors(request_id,trace_id"));
check("internal request trace",source.includes("req.traceId = req.requestId"));
check("trace response header",source.includes('res.setHeader("X-Trace-Id", req.traceId)'));
check("no client trace injection",!source.includes('req.get("x-trace-id")')&&!source.includes('req.headers["x-trace-id"]'));
check("metadata sanitizer",source.includes("sanitizeOperationalMetadata"));
check("sensitive keys redacted",source.includes("delivery.?code|address|customer|payment|payload|response|body"));
check("env secrets redacted",source.includes("DATABASE_URL|AUTH"));
check("structured JSON log",source.includes('log_type: "operational_event"'));
check("transaction trace arg",source.includes("recovery = false,\n  traceId = null"));
check("dispatch trace persisted",source.includes("departed_at,trace_id"));
check("courier trace propagated",source.includes("anotaAiLinks,\n      traceId: req.traceId"));
check("admin trace propagated",source.includes("ifoodLinks: ifoodInspection.accepted,\n      traceId: req.traceId"));
check("dispatch events",source.includes('"dispatch.created"')&&source.includes('"dispatch.replayed"')&&source.includes('"dispatch.released"'));
check("iFood worker events",source.includes('"ifood.dispatch.claimed"')&&source.includes('"ifood.dispatch.sent"')&&source.includes('"ifood.dispatch.retry"')&&source.includes('"ifood.dispatch.failed"')&&source.includes('"ifood.dispatch.completed"'));
check("Anota worker events",source.includes('"anotaai.dispatch.claimed"')&&source.includes('"anotaai.dispatch.sent"')&&source.includes('"anotaai.dispatch.retry"')&&source.includes('"anotaai.dispatch.dead"'));
check("delivery code not traced",!source.includes("metadata: { deliveryCode")&&!source.includes("metadata: { code: deliveryCode"));
check("delivery events",source.includes('"anotaai.delivery.confirmed"')&&source.includes('"ifood.delivery.verify.started"')&&source.includes('"ifood.delivery.verified"'));
check("protected trace endpoint",source.includes('app.get("/api/admin/trace", auth, adminOnly'));
check("three trace filters",source.includes("trace_id, dispatch_id ou order_number"));
check("30 day retention",source.includes("created_at < NOW()-INTERVAL '30 days'"));
check("HTTP errors correlated",source.includes('"http.error"'));
check("smoke requires trace",smoke.includes("missing-trace-id"));
check("smoke verifies timeline",smoke.includes("trace-missing-dispatch-created")&&smoke.includes("trace-missing-dispatch-released"));
check("smoke checks leakage",smoke.includes("trace-secret-leak"));
const failed=checks.filter(x=>!x.ok);
for(const x of checks) console.log(`${x.ok?"PASS":"FAIL"} - ${x.name}`);
console.log(`Trace observability: ${checks.length-failed.length}/${checks.length} checks passed`);
if(failed.length) process.exit(1);
