import fs from "node:fs";

const file = new URL("../render-staging.yaml", import.meta.url);
const yaml = fs.readFileSync(file, "utf8");

const checks = [
  ["staging service is explicit", /name:\s*despachefull-staging\b/.test(yaml)],
  ["staging branch is explicit", /branch:\s*staging\b/.test(yaml) && !/branch:\s*main\b/.test(yaml)],
  ["free web service in Oregon", /type:\s*web\b/.test(yaml) && /plan:\s*free\b/.test(yaml) && /region:\s*oregon\b/.test(yaml)],
  ["deploy waits for CI checks", /autoDeployTrigger:\s*checksPass\b/.test(yaml)],
  ["health check uses app endpoint", /healthCheckPath:\s*\/api\/health\b/.test(yaml)],
  ["existing isolated database is referenced", /key:\s*DATABASE_URL[\s\S]{0,180}fromDatabase:[\s\S]{0,180}name:\s*despachefull-staging-db[\s\S]{0,180}property:\s*connectionString/.test(yaml)],
  ["blueprint does not manage or recreate Postgres", !/^\s*databases\s*:/m.test(yaml)],
  ["database credentials are not hardcoded", !/postgres(?:ql)?:\/\//i.test(yaml)],
  ["session secret is generated by Render", /key:\s*SESSION_SECRET[\s\S]{0,80}generateValue:\s*true/.test(yaml)],
  ["initial admin password stays out of git", /key:\s*ADMIN_PASSWORD[\s\S]{0,80}sync:\s*false/.test(yaml)],
  ["runtime is staging safe mode", /key:\s*APP_ENV[\s\S]{0,80}value:\s*staging/.test(yaml) && /key:\s*STAGING_SAFE_MODE[\s\S]{0,80}value:\s*["']?true["']?/.test(yaml)],
  ["runtime keeps production semantics", /key:\s*NODE_ENV[\s\S]{0,80}value:\s*production/.test(yaml)]
];

let failed = 0;
for (const [label, pass] of checks) {
  console.log(`${pass ? "PASS" : "FAIL"} - ${label}`);
  if (!pass) failed++;
}

if (failed) {
  console.error(`Render staging Blueprint self-test failed: ${failed} check(s).`);
  process.exit(1);
}

console.log(`Render staging Blueprint self-test passed: ${checks.length}/${checks.length}.`);
